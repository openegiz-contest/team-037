/**
 * Привязка координат модели (м; x — восток, y — юг, начало — центр карьера) к реальной местности.
 *
 * Центр и ориентация взяты по контуру карьера «Ақтоғай» в OpenStreetMap (way 773805067):
 * центр ~46,969° с. ш., 79,975° в. д., длинная ось повёрнута на ~50° от направления «восток»
 * (по часовой стрелке на карте), размеры ~3,1 × 2,4 км. Модельный карьер (3 × 1,6 км) кладётся
 * по центру и длинной оси реального; масштаб — метры в метры. Здания модели и условные объекты
 * комбината на снимке стоят не на своих реальных местах.
 */
export const GEO_REF = {
  lat: 46.96911,
  lon: 79.9749,
  /** Поворот длинной оси, градусы (от востока по часовой стрелке на карте). */
  rotDeg: 50.4,
};

const R = (GEO_REF.rotDeg * Math.PI) / 180;
const KX = 111320 * Math.cos((GEO_REF.lat * Math.PI) / 180); // м на градус долготы
const KY = 110540; // м на градус широты

/** Точка модели → [широта, долгота]. */
export function toLatLng(x: number, y: number): [number, number] {
  const xr = x * Math.cos(R) - y * Math.sin(R);
  const yr = x * Math.sin(R) + y * Math.cos(R);
  return [GEO_REF.lat - yr / KY, GEO_REF.lon + xr / KX];
}
